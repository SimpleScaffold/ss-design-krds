#!/usr/bin/env node
/**
 * Split official krds_tokens.css into color vs structure (semantic) bundles.
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const sourcePath = path.join(
  root,
  'assets/krds/resources/css/token/krds_tokens.css'
);
const outDir = path.join(root, 'packages/krds-tailwind/src');

function isColorVariable(line) {
  const m = line.match(/^\s*(--[\w-]+):/);
  if (!m) return false;
  const name = m[1];
  if (name.startsWith('--krds-color-')) return true;
  if (name.includes('-color-')) return true;
  return false;
}

function isStructureVariable(line) {
  const m = line.match(/^\s*(--[\w-]+):/);
  if (!m) return false;
  const name = m[1];
  if (isColorVariable(line)) return false;
  if (
    name.startsWith('--krds-typo-') ||
    name.startsWith('--krds-number-') ||
    name.startsWith('--krds-pc-') ||
    name.startsWith('--krds-mobile-') ||
    name.startsWith('--krds-gap-') ||
    name.startsWith('--krds-padding-') ||
    name.startsWith('--krds-size-') ||
    name.startsWith('--krds-radius-') ||
    name.startsWith('--krds-light-border-width-') ||
    name.startsWith('--krds-high-contrast-border-width-')
  ) {
    return true;
  }
  return false;
}

function isSectionComment(line, tag) {
  return line.includes(`/* ${tag} */`);
}

async function main() {
  const raw = await fs.readFile(sourcePath, 'utf8');
  const lines = raw.split('\n');

  const colorLines = [];
  const structureLines = [];
  let inRoot = false;

  const header = `@charset "utf-8";
/* Auto-generated by scripts/split-krds-tokens.mjs — do not edit */
/* Source: assets/krds/resources/css/token/krds_tokens.css */

`;

  for (const line of lines) {
    if (line.includes(':root {')) {
      inRoot = true;
      colorLines.push(':root {');
      structureLines.push(':root {');
      continue;
    }
    if (inRoot && line.trim() === '}') {
      colorLines.push('}');
      structureLines.push('}');
      inRoot = false;
      continue;
    }
    if (!inRoot) continue;

    const trimmed = line.trim();
    if (!trimmed) continue;

    if (isSectionComment(line, 'PRIMITIVE')) {
      colorLines.push(line);
      structureLines.push(line);
      continue;
    }
    if (
      isSectionComment(line, 'MODE-LIGHT') ||
      isSectionComment(line, 'MODE-HIGH-CONTRAST')
    ) {
      colorLines.push(line);
      continue;
    }
    if (
      isSectionComment(line, 'RESPONSIVE-PC') ||
      isSectionComment(line, 'RESPONSIVE-MOBILE') ||
      isSectionComment(line, 'SEMANTIC')
    ) {
      structureLines.push(line);
      continue;
    }

    if (isColorVariable(line)) {
      colorLines.push(line);
    } else if (isStructureVariable(line)) {
      structureLines.push(line);
    } else if (trimmed.startsWith('/*')) {
      colorLines.push(line);
      structureLines.push(line);
    }
  }

  await fs.mkdir(outDir, { recursive: true });
  await fs.writeFile(
    path.join(outDir, 'tokens-color.css'),
    header + colorLines.join('\n') + '\n',
    'utf8'
  );
  await fs.writeFile(
    path.join(outDir, 'tokens-semantic.css'),
    header + structureLines.join('\n') + '\n',
    'utf8'
  );

  console.log(
    JSON.stringify(
      {
        colorVars: colorLines.filter((l) => l.includes(':')).length,
        structureVars: structureLines.filter((l) => l.includes(':')).length,
        outDir: 'packages/krds-tailwind/src'
      },
      null,
      2
    )
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
