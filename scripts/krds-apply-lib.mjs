import { promises as fs } from 'node:fs';
import path from 'node:path';

const PRIMITIVE_COLOR_RE =
  /^\s*(--krds-color-(?:light|high-contrast)-[\w-]+):\s*(.+);\s*$/;

export async function loadTokenBridgeManifest(krdsRoot) {
  const p = path.join(krdsRoot, 'manifests/token-bridge.json');
  return JSON.parse(await fs.readFile(p, 'utf8'));
}

export async function scanConsumerColorVars(targetDir, maxFiles = 80) {
  const found = new Map();
  const varRe = /(--[\w-]+)\s*:\s*([^;]+);/g;
  const cssRe = /\.(css|scss|less)$/i;

  async function walk(dir, depth = 0) {
    if (depth > 6) return;
    let entries;
    try {
      entries = await fs.readdir(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const ent of entries) {
      if (found.size >= maxFiles) return;
      const full = path.join(dir, ent.name);
      if (ent.isDirectory()) {
        if (
          ['node_modules', '.git', 'dist', 'build', '.next', 'coverage'].includes(
            ent.name
          )
        ) {
          continue;
        }
        await walk(full, depth + 1);
      } else if (cssRe.test(ent.name)) {
        const text = await fs.readFile(full, 'utf8');
        let m;
        while ((m = varRe.exec(text)) !== null) {
          const name = m[1];
          const val = m[2].trim();
          if (
            /color|primary|secondary|gray|neutral|surface|background|text|danger|success|warning|info|accent|brand/i.test(
              name
            ) &&
            !name.startsWith('--krds-')
          ) {
            if (!found.has(name)) found.set(name, val);
          }
        }
      }
    }
  }

  await walk(targetDir);
  return found;
}

function familyForKrdsVar(varName, manifest) {
  for (const [key, cfg] of Object.entries(manifest.paletteFamilies)) {
    if (varName.startsWith(cfg.krdsPrefix)) return { key, cfg };
  }
  if (varName.includes('-high-contrast-')) {
    const lightName = varName.replace('-high-contrast-', '-light-');
    return familyForKrdsVar(lightName, manifest);
  }
  return null;
}

function pickConsumerVar(varName, consumerVars, manifest) {
  const family = familyForKrdsVar(varName, manifest);
  if (!family) return null;
  for (const candidate of family.cfg.consumerCandidates) {
    if (consumerVars.has(candidate)) return candidate;
  }
  return family.cfg.consumerCandidates[0] || null;
}

function isPrimitiveColorLine(line) {
  const m = line.match(PRIMITIVE_COLOR_RE);
  if (!m) return false;
  const name = m[1];
  if (name.includes('-light-color-') || name.includes('-high-contrast-color-')) {
    return false;
  }
  return name.startsWith('--krds-color-light-') || name.startsWith('--krds-color-high-contrast-');
}

export async function generateBridgeCss(krdsRoot, consumerVars, options = {}) {
  const manifest = await loadTokenBridgeManifest(krdsRoot);
  const tokensColorPath = path.join(
    krdsRoot,
    'packages/krds-tailwind/src/tokens-color.css'
  );
  let raw = await fs.readFile(tokensColorPath, 'utf8');
  if (!raw.includes('MODE-LIGHT')) {
    const split = path.join(krdsRoot, 'scripts/split-krds-tokens.mjs');
    const { execSync } = await import('node:child_process');
    execSync(`node "${split}"`, { cwd: krdsRoot, stdio: 'pipe' });
    raw = await fs.readFile(tokensColorPath, 'utf8');
  }

  const lines = raw.split('\n');
  const out = [
    '@charset "utf-8";',
    '/**',
    ' * KRDS color bridge — project palette → --krds-color-* (for output.css).',
    ' * Generated by krds:apply --preserve-colors all',
    ' * Do NOT import tokens-color.css when this file is present.',
    ' */',
    ':root {'
  ];

  const mapped = new Set();
  let inRoot = false;

  for (const line of lines) {
    if (line.includes(':root {')) {
      inRoot = true;
      continue;
    }
    if (inRoot && line.trim() === '}') break;
    if (!inRoot) continue;

    const trimmed = line.trim();
    if (!trimmed) continue;

    if (isPrimitiveColorLine(line)) {
      const m = line.match(PRIMITIVE_COLOR_RE);
      const name = m[1];
      const defaultVal = m[2].trim();
      const consumer = pickConsumerVar(name, consumerVars, manifest);
      let value = defaultVal;
      if (consumer && (consumerVars.has(consumer) || options.wrapAllPrimitives)) {
        value = `var(${consumer}, ${defaultVal})`;
        mapped.add(name);
      }
      out.push(`  ${name}: ${value};`);
    } else {
      out.push(line);
    }
  }

  out.push('}');
  out.push('');
  out.push(
    '/* Mapped primitives: ' +
      mapped.size +
      ' — edit manifests/token-bridge.json to tune candidates */'
  );
  return out.join('\n');
}

export async function detectStack(targetDir) {
  const pkgPath = path.join(targetDir, 'package.json');
  let pkg = {};
  try {
    pkg = JSON.parse(await fs.readFile(pkgPath, 'utf8'));
  } catch {
    return null;
  }
  const deps = { ...pkg.dependencies, ...pkg.devDependencies };
  if (deps.react || deps['react-dom'] || deps.vue || deps['@vue/runtime-core']) {
    if (deps.tailwindcss || deps['@tailwindcss/cli']) return 'react';
    return 'react';
  }
  if (deps.tailwindcss || deps['@tailwindcss/cli']) return 'tailwind';
  const hasTwConfig = await fileExists(path.join(targetDir, 'tailwind.config.js'));
  const hasTwTs = await fileExists(path.join(targetDir, 'tailwind.config.ts'));
  if (hasTwConfig || hasTwTs) return 'tailwind';
  return 'vanilla';
}

async function fileExists(p) {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

